import pandas as pd
from sklearn.linear_model import LogisticRegression

"""2. Load the dataset"""

df = pd.read_csv("https://raw.githubusercontent.com/ARI3217/datasets/main/prices.csv")
display (df.head())

"""3. Adding the VAT to the prices (overwriting the original data)"""

df["price"] = df["price"] * 1.18
display (df.head ())

"""4. Train the model using Logistic Regression"""

# Cell 3: train the model
model = LogisticRegression(random_state=42)
model.fit(df[["price"]], df["sold"]);
print ("Model Trained")

"""4. Predict the sales for a new item - Ceramic fruit bowl priced at €20.00 exc. VAT"""

new_item = pd.DataFrame({
    "description": ["Ceramic fruit bowl, hand-painted"],
    "price": [20.00 * 1.18],
})
probability = model.predict_proba(new_item[["price"]])[0][1]

print(f"Average training price: EUR {df['price'].mean():.2f}")
print(f"New item: {new_item['description'][0]}")
print(f"Probability that the new item sells: {probability:.3f}")

